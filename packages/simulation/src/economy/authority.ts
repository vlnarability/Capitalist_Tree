/**
 * Central monetary authority (TDD §10.3, GDD §6.2).
 *
 * The authority is the virtual "mint" — it issues currency in response to
 * CurrencyIssuanceRequests (emitted by `harvest-leaves` via P1's
 * HarvestSystem), and it sinks currency via explicit monetary operations
 * (taxes, fees, central-bank interventions). The authority's net position
 * is implied by `totalIssued - totalSinks` — it is NOT an entry in
 * `economy.accounts`.
 *
 * CurrencyIssuanceRequest consumption contract (TDD §10.2):
 *   - P1's `harvestLeaves` emits a request on `tree.pendingIssuances`:
 *       { treeId, amount: bigint-string, currencyId, source: 'harvest-leaves' }
 *   - P3a's EconomySystem drains `originalTree.pendingIssuances` each tick
 *     and calls `requestIssuance()` for each.
 *   - The requestId is derived deterministically from (saveId, simSecond,
 *     queueIndex) so the same pendingIssuance in the same step always
 *     produces the same requestId — across save/load, a re-processed
 *     request is detected as a duplicate and skipped (idempotency,
 *     TDD §10.3 — "Currency production must be accounted for exactly once").
 *
 * Distinguishes (TDD §10.2 — "The implementation must distinguish"):
 *   - Physical leaves currently attached to the tree
 *     (tracked by `TreeState.foliage.currentLeaves`).
 *   - Currency generated by harvesting
 *     (queued on `tree.pendingIssuances` as `CurrencyIssuanceRequest`).
 *   - Currency in circulation
 *     (`economy.monetarySupply` = sum of all non-authority account balances).
 *   - Currency held by the player
 *     (`economy.accounts[player:personal].balance`, mirrored on
 *     `player.personalCash` by the EconomySystem).
 *   - Currency held by other participants
 *     (`economy.accounts[external:*]`).
 */
import type {
  CurrencyIssuanceRequest,
  GameState,
  SimulationEvent,
  TreeState,
} from '@capitalist-tree/shared';
import {
  PROVISIONAL_ECONOMY_AUTHORITY_ACCOUNT_ID,
  PROVISIONAL_ECONOMY_PLAYER_ACCOUNT_ID,
  PROVISIONAL_ECONOMY_CATEGORY_ISSUANCE,
} from '@capitalist-tree/shared';
import {
  isRequestProcessed,
  transfer,
  validateAmount,
} from './ledger.js';
import { InvalidAmountError } from './errors.js';

/**
 * Derive the deterministic requestId for a pending issuance.
 *
 * Same `(saveId, simSecond, index)` triple always produces the same
 * requestId, even across save/load. This is the idempotency key: the
 * EconomySystem records it in `economy.processedRequestIds` when it
 * processes (or rejects) the request, so a re-processed request never
 * double-issues money.
 *
 * `saveId` comes from `state.metadata.saveId`. `simSecond` is the current
 * `ctx.now` (the simulation second at which the EconomySystem is running —
 * this is the post-TimeSystem tick value, so it advances each step). `index`
 * is the position of the request in `tree.pendingIssuances` at the start
 * of the drain.
 */
export function issuanceRequestId(
  saveId: string,
  simSecond: number,
  index: number,
): string {
  return `issuance:${saveId}:${simSecond}:${index}`;
}

/** Optional parameters for `requestIssuance()` / `drainPendingIssuances()`. */
export interface IssuanceOptions {
  /** Destination account id. Defaults to `player:personal` (the original
   *  tree's leaves become the player's currency). Future phases may route
   *  to a business account for non-original trees (P3d). */
  destinationAccount?: string;
  /** Issuance policy (from content/monetary-policy). If omitted, NO caps
   *  are checked — the request is authorized unless it fails amount
   *  validation or is a duplicate. The EconomySystem always passes the
   *  DEFAULT_ISSUANCE_POLICY from content. */
  policy?: {
    maxPerRequest: string | null;
    maxTotal: string | null;
    issuanceFeeFraction: number;
  };
}

/** Result of processing one (or many) issuance requests. */
export interface IssuanceResult {
  state: GameState;
  events: SimulationEvent[];
}

/**
 * Process a single CurrencyIssuanceRequest.
 *
 * Steps (TDD §10.3 — "Currency production must be accounted for exactly once"):
 *   1. **Idempotency check**: if `requestId` is already in
 *      `processedRequestIds`, emit `issuance-rejected` with reason
 *      `'duplicate-request'` and return — NO money movement, NO state
 *      change beyond the rejection event. This is the defensive idempotency
 *      net: the same pendingIssuance re-processed across a save/load is
 *      caught here.
 *   2. **Validate amount**: must be a positive bigint string. If invalid,
 *      emit `issuance-rejected` with reason `'invalid-amount'`.
 *   3. **Apply issuance policy** (from `options.policy`): check `maxPerRequest`
 *      and `maxTotal` caps. If exceeded, emit `issuance-rejected` with the
 *      policy reason.
 *   4. **Authorized**: call `transfer()` to credit the destination,
 *      increment `monetarySupply` and `totalIssued`, record an `issuance`
 *      transaction tagged with `requestId`, and mark `requestId` as processed.
 *      Emit `issuance-authorized` + `transaction-recorded`.
 *
 * Pure: returns a new state, never mutates input. Deterministic: same state +
 * same request + same requestId → same output. The EconomySystem's per-tick
 * drain never throws — all rejections are converted into `issuance-rejected`
 * events so the simulation continues.
 *
 * The destination account is currently always `player:personal` (the original
 * tree's leaves become the player's currency). The function also mirrors the
 * new balance to `player.personalCash` so existing code that reads that field
 * (e.g. P0/P1/P2 tests, the P4 renderer) keeps working. P3c's PersonalSystem
 * may refactor this coupling.
 */
export function requestIssuance(
  state: GameState,
  request: CurrencyIssuanceRequest,
  requestId: string,
  timestamp: number,
  options?: IssuanceOptions,
): IssuanceResult {
  // 1. Idempotency check.
  if (isRequestProcessed(state, requestId)) {
    return {
      state,
      events: [
        {
          type: 'issuance-rejected',
          at: timestamp,
          payload: {
            requestId,
            treeId: request.treeId,
            amount: request.amount,
            currencyId: request.currencyId,
            source: request.source,
            reason: 'duplicate-request',
            message: `Issuance request ${requestId} already processed — refusing to double-issue.`,
          },
        },
      ],
    };
  }

  // 2. Validate amount.
  let amount: bigint;
  try {
    amount = validateAmount(request.amount);
  } catch (err) {
    const reason =
      err instanceof InvalidAmountError ? err.reason : 'invalid-amount';
    return {
      state,
      events: [
        {
          type: 'issuance-rejected',
          at: timestamp,
          payload: {
            requestId,
            treeId: request.treeId,
            amount: request.amount,
            currencyId: request.currencyId,
            source: request.source,
            reason: 'invalid-amount',
            message: `Issuance amount "${request.amount}" is not a valid positive bigint string (${reason}).`,
          },
        },
      ],
    };
  }

  // 3. Apply policy.
  if (options?.policy) {
    const p = options.policy;
    if (p.maxPerRequest !== null) {
      if (amount > BigInt(p.maxPerRequest)) {
        return {
          state,
          events: [
            {
              type: 'issuance-rejected',
              at: timestamp,
              payload: {
                requestId,
                treeId: request.treeId,
                amount: request.amount,
                currencyId: request.currencyId,
                source: request.source,
                reason: 'per-request-limit-exceeded',
                message: `Issuance amount ${request.amount} exceeds per-request cap ${p.maxPerRequest}.`,
              },
            },
          ],
        };
      }
    }
    if (p.maxTotal !== null) {
      const total = BigInt(state.economy.totalIssued);
      if (total + amount > BigInt(p.maxTotal)) {
        return {
          state,
          events: [
            {
              type: 'issuance-rejected',
              at: timestamp,
              payload: {
                requestId,
                treeId: request.treeId,
                amount: request.amount,
                currencyId: request.currencyId,
                source: request.source,
                reason: 'cumulative-limit-exceeded',
                message: `Issuance would push total issued ${total + amount} beyond cap ${p.maxTotal}.`,
              },
            },
          ],
        };
      }
    }
  }

  // 4. Authorized — issue via transfer().
  const destinationAccount =
    options?.destinationAccount ?? PROVISIONAL_ECONOMY_PLAYER_ACCOUNT_ID;
  const nextState = transfer(state, {
    sourceAccount: PROVISIONAL_ECONOMY_AUTHORITY_ACCOUNT_ID,
    destinationAccount,
    amount: amount.toString(10),
    category: PROVISIONAL_ECONOMY_CATEGORY_ISSUANCE,
    description: `Issuance from harvest (tree=${request.treeId}, source=${request.source})`,
    timestamp,
    requestId,
  });

  // Mirror the new balance to player.personalCash if the destination was
  // the player:personal account. (PersonalSystem in P3c may refactor this
  // — for P3a we keep both fields in sync so existing engine.advance tests
  // that read player.personalCash still pass.)
  let synced = nextState;
  if (destinationAccount === PROVISIONAL_ECONOMY_PLAYER_ACCOUNT_ID) {
    const newBalance = nextState.economy.accounts.find(
      (a) => a.id === PROVISIONAL_ECONOMY_PLAYER_ACCOUNT_ID,
    )?.balance;
    if (newBalance !== undefined && newBalance !== nextState.player.personalCash) {
      synced = {
        ...nextState,
        player: { ...nextState.player, personalCash: newBalance },
      };
    }
  }

  // The new transaction is the last entry in nextState.economy.transactions
  // (transfer() always appends exactly one).
  const record = synced.economy.transactions[synced.economy.transactions.length - 1]!;

  return {
    state: synced,
    events: [
      {
        type: 'issuance-authorized',
        at: timestamp,
        payload: {
          requestId,
          treeId: request.treeId,
          destinationAccount,
          amount: amount.toString(10),
          currencyId: request.currencyId,
          source: request.source,
        },
      },
      {
        type: 'transaction-recorded',
        at: timestamp,
        payload: { record },
      },
    ],
  };
}

/**
 * Drain a tree's pendingIssuances queue.
 *
 * For each CurrencyIssuanceRequest in `tree.pendingIssuances`, derive a
 * deterministic requestId via `issuanceRequestId(saveId, simSecond, index)`
 * and call `requestIssuance()`. Returns the new state with the queue
 * cleared, plus all events emitted (authorized + rejected).
 *
 * Idempotency: if a request's requestId is already in `processedRequestIds`
 * (e.g. the same step was processed before a save/load and is being re-run),
 * the duplicate is rejected (no money issued) and an `issuance-rejected`
 * event is emitted. The queue is still cleared.
 *
 * Determinism: same `(state, saveId, simSecond)` → same final state + same
 * transaction log + same events. Verified by economy.test.ts.
 *
 * Currently only supports the original tree (P1). Future phases that add
 * additional trees in `state.trees[]` would call this per-tree.
 */
export function drainPendingIssuances(
  state: GameState,
  tree: TreeState,
  saveId: string,
  simSecond: number,
  options?: IssuanceOptions,
): IssuanceResult {
  let next: GameState = state;
  const events: SimulationEvent[] = [];
  const queue = tree.pendingIssuances;

  for (let i = 0; i < queue.length; i++) {
    const req = queue[i]!;
    const requestId = issuanceRequestId(saveId, simSecond, i);
    const result = requestIssuance(next, req, requestId, simSecond, options);
    next = result.state;
    events.push(...result.events);
  }

  // Clear the tree's pendingIssuances queue (whether authorized or rejected).
  // We clear even rejected ones to avoid infinite accumulation — the
  // rejection event provides the audit trail.
  if (tree.id === state.originalTree.id) {
    next = {
      ...next,
      originalTree: { ...next.originalTree, pendingIssuances: [] },
    };
  }
  // Future: additional trees in `state.trees[]` would be cleared here.

  return { state: next, events };
}

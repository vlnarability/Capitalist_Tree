/**
 * Köppen-Geiger climate zone catalog (GAP-17 / DR-11 — Phase 1).
 *
 * Pure data — the 31 Köppen-Geiger climate types as realistic exemplar zones,
 * grounded in the Kottek et al. 2006 classification (NOAA Jetstream Köppen
 * subdivisions: the attached `koppen_2006.png` map). Every zone's temperature +
 * precipitation profile is a realistic mid-range value for its real-world
 * exemplar region, consistent with the published Köppen criteria (driest-month
 * 60 mm, 18 °C / 10 °C / 22 °C boundaries, the 3:1 winter:summer precipitation
 * ratio for Mediterranean zones, etc.).
 *
 * Phase 3 (DR-11) is WIRED — the WeatherSystem reads these fields every tick:
 * `seasonalBaseTemp` feeds the local temperature (effects.ts),
 * `koppenCode`/`frostRisk`/`heatStressRisk` drive the per-zone transition
 * matrix biases (transition-matrices.ts), `seasonality` drives the season
 * calendar (time-system.ts), + `precipitation.annualMm` is the photosynthesis
 * water-stress Liebig signal (photosynthesis.ts:147). See
 * climate-effect-wiring.test.ts for the acceptance coverage (BWh vs Af water
 * balance + temperature). Phases 4 (highland lapse) + 5 (runtime frost
 * re-derivation) are also done.
 *
 * The default starting climate (`climate:temperate`) lives in
 * `climate-baselines.ts` — it is a warm-Dfb gameplay default (kept byte-identical
 * for back-compat) and is NOT one of these pure exemplars; a strict pure-Dfb
 * exemplar (`climate:dfb`, 7/19/7/-5) is included below.
 *
 * Tree species per zone (GAP-17 §5b) ship in Phase 2 — the species catalog
 * expands around the existing White Oak (Dfa/Dfb) + Eastern Hemlock (Dfb/Dfc).
 */
import type { ClimateZone } from '@capitalist-tree/shared';
import { PROVISIONAL_WEATHER_CLIMATE_SHIFT_BASELINE_TEMP_C } from '@capitalist-tree/shared';

/**
 * Default climate-shift hook for the Köppen exemplars. Mirrors the existing
 * `TEMPERATE_CLIMATE` hook: the ~14 °C global average is the baseline; 1:1
 * warming shifts the baseline temperature; +2 % drought probability per degree.
 * The hook is a no-op until P6 plumbs a real global-temperature trajectory, so
 * these values are placeholders for content completeness, not active tuning.
 */
const DEFAULT_CLIMATE_SHIFT_HOOK = {
  baselineTempC: PROVISIONAL_WEATHER_CLIMATE_SHIFT_BASELINE_TEMP_C,
  tempShiftPerDegreeC: 1.0,
  droughtProbShiftPerDegreeC: 0.02,
} as const;

/** Helper: fill the default climate-shift hook so each zone literal stays terse. */
function zone(z: Omit<ClimateZone, 'climateShiftHook'>): ClimateZone {
  return { ...z, climateShiftHook: DEFAULT_CLIMATE_SHIFT_HOOK };
}


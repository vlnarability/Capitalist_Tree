/**
 * GAP-31 (DR-13) — Analytics event schema.
 *
 * Local-only, on-device analytics (see docs/reviews/GAP-31-analytics-design.md).
 * Every analytics event is structured + versioned so the shape can evolve
 * without breaking historical records or exports.
 *
 * The simulation engine NEVER imports this schema directly — the collector
 * (apps/web) subscribes to the existing SimulationEvent stream + shapes events
 * into this schema. This keeps the sim pure (zero analytics coupling) + makes
 * the collector a no-op in unit tests (no subscriber attached).
 */
import { z } from 'zod';

/** Bump when the AnalyticsEvent shape changes in a backward-incompatible way. */
export const ANALYTICS_SCHEMA_VERSION = 1;

export const analyticsEventCategorySchema = z.enum([
  'gameplay',
  'simulation',
  'performance',
  'error',
]);

export type AnalyticsEventCategory = z.infer<typeof analyticsEventCategorySchema>;

export const analyticsEventSchema = z.object({
  /** Opaque unique id (caller-supplied or generated by the collector). */
  id: z.string().min(1),
  /** Analytics schema version —独立 of the save schema version. */
  schemaVersion: z.literal(ANALYTICS_SCHEMA_VERSION),
  /** Wall-clock ms when the event was recorded (Date.now() at collect time). */
  timestamp: z.number().int().nonnegative(),
  /** In-sim time in ms (clock.elapsedSeconds × 1000) when the event occurred,
   *  or 0 if the event is out-of-sim (e.g. a load failure before the engine
   *  booted). */
  simulationTime: z.number().nonnegative(),
  category: analyticsEventCategorySchema,
  /** Stable event name, e.g. 'tree-died', 'objective-completed', 'save-loaded'. */
  event: z.string().min(1),
  /** Optional structured payload (cause, objective id, error message, …). */
  data: z.record(z.string(), z.unknown()).optional(),
});

export type AnalyticsEvent = z.infer<typeof analyticsEventSchema>;

/** A category-scoped filter for the store query API. */
export interface AnalyticsQuery {
  category?: AnalyticsEventCategory;
  /** Only events with this name. */
  event?: string;
  /** Only events at-or-after this wall-clock ms. */
  since?: number;
  /** Maximum number of events to return (most-recent first). */
  limit?: number;
}
